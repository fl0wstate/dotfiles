return {
    {
        "folke/persistence.nvim",
        keys = {
            {
                "<leader>qD",
                function()
                    for _, file in ipairs(vim.fn.glob(vim.fn.stdpath("state") .. "/sessions/.vim", true, true)) do
                        vim.fn.delete(file)
                    end
                    vim.notify("All sessions deleted", vim.log.levels.INFO)
                end,
                desc = "Delete All Sessions",
            },
        },
    },
    {
        "ThePrimeagen/harpoon",
        branch = "harpoon2",
        opts = {
            menu = {
                width = vim.api.nvim_win_get_width(0) - 4,
            },
            settings = {
                save_on_toggle = true,
            },
        },
        keys = function()
            local keys = {
                {
                    "<leader>H",
                    function()
                        require("harpoon"):list():add()
                    end,
                    desc = "Harpoon File",
                },
                {
                    "<leader>h",
                    function()
                        local harpoon = require("harpoon")
                        harpoon.ui:toggle_quick_menu(harpoon:list())
                    end,
                    desc = "Harpoon Quick Menu",
                },
            }

            for i = 1, 5 do
                table.insert(keys, {
                    "<leader>" .. i,
                    function()
                        require("harpoon"):list():select(i)
                    end,
                    desc = "Harpoon to File " .. i,
                })
            end
            return keys
        end,
    },
}
